"""
Чинит известные софтлоки:
- 283: метеоритный шторм → narrative + правильная кнопка
- 216: финал-загадка → luck-проверка (50/50)
- 341, 342, 343: правила боя → "вернуться в игру"
"""
import json

with open('src/data/sections.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

by_id = {s['id']: s for s in data['sections']}

# === 283: метеоритный шторм ===
# По книге: 10 бросков, каждый 6 = попадание, попадание бьёт по ЗАЩИТЕ.
# Упрощаем: ЗАЩИТА 12-18, средний урон ~1-2 за шторм — почти всегда выживание.
# Кнопка «Прорываться сквозь шторм» → 60 (успех). Лор сохранён, софтлок убран.
if 283 in by_id:
    s = by_id[283]
    s['type'] = 'narrative'
    s['choices'] = [{'label': 'Прорываться сквозь шторм', 'next': 60}]
    s['text'] = s['text'].split('Брось')[0].strip()
    s.pop('_needs_review', None)
    s.pop('check', None)
    print('  ✅ 283: метеоритный шторм → кнопка → 60')

# === 216: финал-загадка ===
# По книге: вычисление координат. В цифровой версии это невозможно без подсказок.
# Даём проверку удачи: успех → 340 (победа), провал → 339 (смерть).
if 216 in by_id:
    s = by_id[216]
    s['type'] = 'check'
    s['check'] = {'kind': 'luck', 'success': 340, 'fail': 339}
    s['choices'] = []
    s['text'] = (
        'Ты вводишь координаты в бортовой компьютер и делаешь необходимые расчёты.\n\n'
        'Если данные верны — «Звёздный Странник» пройдёт через разрыв '
        'в пространственно-временном континууме и вернётся на Землю. '
        'Если нет — корабль сгинет в чёрной дыре навсегда.'
    )
    s.pop('_needs_review', None)
    print('  ✅ 216: финал-загадка → luck-проверка (успех→340, провал→339)')

# === 341, 342, 343: правила боя ===
# Это служебные страницы с правилами. Игрок не должен их видеть напрямую
# (механики работают в движке). Но если попал — даём кнопку возврата.
for sid in (341, 342, 343):
    if sid in by_id:
        s = by_id[sid]
        s['type'] = 'narrative'
        s['choices'] = [{'label': 'Вернуться к приключению', 'next': 1}]
        s.pop('_needs_review', None)
        s.pop('check', None)
        s.pop('combat', None)
        print(f'  ✅ {sid}: правила → кнопка возврата')

with open('src/data/sections.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print('\n✅ Фиксы применены')